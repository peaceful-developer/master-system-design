/**
 * Turns loaded content into the files under src/generated/. Output is fully
 * deterministic (stable ordering, no timestamps) and only changed files are
 * rewritten, so `ng serve` rebuilds only what changed.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import type {
  CaseStudyMeta,
  CompiledDrill,
  ExampleMeta,
  ExerciseMeta,
  ExerciseParent,
  LessonMeta,
  PlaybookMeta,
  RoutesFile,
} from '../content-types';
import { PHASE_IDS } from '../schemas';
import type { DocItem, LoadedContent } from './load';
import { allRoutes, routeFor } from './routes';
import { buildSearchIndex, searchDocs } from './search-index';

export const MASCOT_POSES = ['idle', 'thinking', 'cheer', 'puzzled', 'sleep', 'fly'] as const;

export type OutputFiles = Map<string, string>;

const HEADER = '// Generated by scripts/build-content.ts from content/. Do not edit.\n';
const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;
const byOrderThenSlug = (a: { order: number; slug: string }, b: { order: number; slug: string }) =>
  a.order - b.order || a.slug.localeCompare(b.slug);

function meta<T extends object>(item: DocItem<T>, url: string): T & { file: string; url: string } {
  return { ...item.data, file: item.file, url };
}

export function buildOutputs(c: LoadedContent): OutputFiles {
  const files: OutputFiles = new Map();
  const phaseIndex = (phase: string) => PHASE_IDS.indexOf(phase as (typeof PHASE_IDS)[number]);

  const lessons = [...c.lessons].sort(
    (a, b) =>
      phaseIndex(a.data.phase) - phaseIndex(b.data.phase) || byOrderThenSlug(a.data, b.data),
  );
  const caseStudies = [...c.caseStudies].sort((a, b) => byOrderThenSlug(a.data, b.data));
  const playbooks = [...c.playbooks].sort((a, b) => byOrderThenSlug(a.data, b.data));
  const examples = [...c.examples].sort((a, b) => a.data.slug.localeCompare(b.data.slug));
  const quizzes = [...c.quizzes].sort((a, b) => a.data.id.localeCompare(b.data.id));
  const drills = [...c.drills].sort((a, b) => a.data.id.localeCompare(b.data.id));
  const diagrams = [...c.diagrams].sort((a, b) => a.data.id.localeCompare(b.data.id));

  const lessonMeta: LessonMeta[] = lessons.map((l) =>
    meta(l, routeFor({ kind: 'lesson', phase: l.data.phase, slug: l.data.slug })),
  );
  const caseStudyMeta: CaseStudyMeta[] = caseStudies.map((s) =>
    meta(s, routeFor({ kind: 'case-study', slug: s.data.slug })),
  );
  const playbookMeta: PlaybookMeta[] = playbooks.map((p) =>
    meta(p, routeFor({ kind: 'playbook', slug: p.data.slug })),
  );
  const exampleMeta: ExampleMeta[] = examples.map((e) =>
    meta(e, routeFor({ kind: 'example', slug: e.data.slug })),
  );

  const parents = new Map<string, ExerciseParent[]>();
  const addParents = (
    kind: ExerciseParent['kind'],
    items: { exercises: string[]; title: string; url: string }[],
  ) => {
    for (const item of items) {
      for (const id of item.exercises) {
        parents.set(id, [...(parents.get(id) ?? []), { kind, title: item.title, url: item.url }]);
      }
    }
  };
  addParents('lesson', lessonMeta);
  addParents('playbook', playbookMeta);
  addParents('case-study', caseStudyMeta);

  const exercises: ExerciseMeta[] = [
    ...quizzes.map((q) => ({ id: q.data.id, kind: 'quiz' as const, data: q.data })),
    ...drills.map((d) => ({ id: d.data.id, kind: 'drill' as const, data: d.data })),
  ]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(({ id, kind, data }) => ({
      id,
      kind,
      title: data.title,
      topics: data.topics,
      difficulty: data.difficulty,
      url: routeFor({ kind: 'exercise', id }),
      usedBy: parents.get(id) ?? [],
    }));

  const glossary = [...(c.glossary?.data.terms ?? [])].sort((a, b) =>
    a.term.localeCompare(b.term, 'en'),
  );

  files.set(
    'manifest.ts',
    `${HEADER}import type {
  CaseStudyMeta,
  ComponentDef,
  ExampleMeta,
  ExerciseMeta,
  GlossaryTerm,
  LearningPath,
  LessonMeta,
  PlaybookMeta,
} from '@content/types';

export const PATH: LearningPath = ${json(c.path?.data ?? { phases: [] }).trimEnd()};

export const LESSONS: LessonMeta[] = ${json(lessonMeta).trimEnd()};

export const CASE_STUDIES: CaseStudyMeta[] = ${json(caseStudyMeta).trimEnd()};

export const PLAYBOOKS: PlaybookMeta[] = ${json(playbookMeta).trimEnd()};

export const EXAMPLES: ExampleMeta[] = ${json(exampleMeta).trimEnd()};

export const EXERCISES: ExerciseMeta[] = ${json(exercises).trimEnd()};

export const GLOSSARY: GlossaryTerm[] = ${json(glossary).trimEnd()};

export const COMPONENTS: ComponentDef[] = ${json(c.components?.data.components ?? []).trimEnd()};
`,
  );

  // Item bodies, one lazily imported JSON chunk each.
  const loaderEntries: Record<string, { key: string; path: string }[]> = {
    lesson: [],
    caseStudy: [],
    playbook: [],
    example: [],
    quiz: [],
    drill: [],
    diagram: [],
  };
  const addItem = (group: string, dir: string, key: string, fileKey: string, body: unknown) => {
    const path = `items/${dir}/${fileKey}.json`;
    files.set(path, json(body));
    loaderEntries[group]!.push({ key, path });
  };
  lessons.forEach((l, i) => {
    const key = `${l.data.phase}/${l.data.slug}`;
    addItem('lesson', 'lesson', key, `${l.data.phase}--${l.data.slug}`, {
      ...lessonMeta[i],
      ...l.doc,
    });
  });
  caseStudies.forEach((s, i) =>
    addItem('caseStudy', 'case-study', s.data.slug, s.data.slug, { ...caseStudyMeta[i], ...s.doc }),
  );
  playbooks.forEach((p, i) =>
    addItem('playbook', 'playbook', p.data.slug, p.data.slug, { ...playbookMeta[i], ...p.doc }),
  );
  examples.forEach((e, i) =>
    addItem('example', 'example', e.data.slug, e.data.slug, { ...exampleMeta[i], ...e.doc }),
  );
  quizzes.forEach((q) => addItem('quiz', 'quiz', q.data.id, q.data.id, q.data));
  drills.forEach((d) => {
    const { id, title, topics, difficulty, givens, questions } = d.data;
    const compiled: CompiledDrill = {
      id,
      title,
      topics,
      difficulty,
      givens,
      questions,
      scenarioHtml: d.scenarioHtml,
      solutionHtml: d.solutionHtml,
    };
    addItem('drill', 'drill', d.data.id, d.data.id, compiled);
  });
  diagrams.forEach((d) => addItem('diagram', 'diagram', d.data.id, d.data.id, d.data));

  const TYPES: Record<string, string> = {
    lesson: 'CompiledLesson',
    caseStudy: 'CompiledCaseStudy',
    playbook: 'CompiledPlaybook',
    example: 'CompiledExample',
    quiz: 'CompiledQuiz',
    drill: 'CompiledDrill',
    diagram: 'Diagram',
  };
  const groups = Object.entries(loaderEntries).map(([group, entries]) => {
    const type = TYPES[group]!;
    const lines = entries.map(
      ({ key, path }) =>
        `    '${key}': () => import('./${path}').then((m) => m.default as unknown as ${type}),`,
    );
    return `  ${group}: {\n${lines.join('\n')}${lines.length ? '\n' : ''}  },`;
  });
  files.set(
    'loaders.ts',
    `${HEADER}import type {
  CompiledCaseStudy,
  CompiledDrill,
  CompiledExample,
  CompiledLesson,
  CompiledPlaybook,
  CompiledQuiz,
  Diagram,
} from '@content/types';

type Loaders<T> = Record<string, () => Promise<T>>;

export const LOADERS: {
  lesson: Loaders<CompiledLesson>;
  caseStudy: Loaders<CompiledCaseStudy>;
  playbook: Loaders<CompiledPlaybook>;
  example: Loaders<CompiledExample>;
  quiz: Loaders<CompiledQuiz>;
  drill: Loaders<CompiledDrill>;
  diagram: Loaders<Diagram>;
} = {
${groups.join('\n')}
};
`,
  );

  const iconEntries = [...c.icons.entries()].sort(([a], [b]) => a.localeCompare(b));
  const icons = Object.fromEntries(iconEntries.map(([name, icon]) => [name, icon.body]));
  const iconElements = Object.fromEntries(iconEntries.map(([name, icon]) => [name, icon.elements]));
  files.set(
    'icons.ts',
    `${HEADER}export interface IconElement {
  tag: string;
  attrs: Record<string, string>;
}

export const ICONS: Record<string, string> = ${json(icons).trimEnd()};

export const ICON_ELEMENTS: Record<string, IconElement[]> = ${json(iconElements).trimEnd()};
`,
  );

  const mascot = Object.fromEntries(
    MASCOT_POSES.filter((pose) => c.figures.has(`mascot-${pose}`)).map((pose) => [
      pose,
      c.figures.get(`mascot-${pose}`)!.svg,
    ]),
  );
  files.set(
    'mascot.ts',
    `${HEADER}export type MascotPose = ${MASCOT_POSES.map((p) => `'${p}'`).join(' | ')};

export const MASCOT: Partial<Record<MascotPose, string>> = ${json(mascot).trimEnd()};
`,
  );

  files.set('search-index.json', `${buildSearchIndex(searchDocs(c))}\n`);

  const routes: RoutesFile = {
    all: allRoutes(c),
    params: {
      lessons: lessons.map((l) => ({ phase: l.data.phase, lesson: l.data.slug })),
      caseStudies: caseStudies.map((s) => ({ slug: s.data.slug })),
      playbooks: playbooks.map((p) => ({ slug: p.data.slug })),
      examples: examples.map((e) => ({ slug: e.data.slug })),
      exercises: exercises.map((e) => ({ id: e.id })),
    },
  };
  files.set('routes.json', json(routes));
  return files;
}

function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

/** Writes changed files, deletes stale ones; returns how many files were written. */
export function writeOutputs(outDir: string, files: OutputFiles): number {
  let written = 0;
  for (const [rel, body] of files) {
    const path = join(outDir, rel);
    if (existsSync(path) && readFileSync(path, 'utf8') === body) continue;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    written++;
  }
  for (const path of listFiles(outDir)) {
    const rel = relative(outDir, path).split(sep).join('/');
    if (!files.has(rel)) unlinkSync(path);
  }
  return written;
}
